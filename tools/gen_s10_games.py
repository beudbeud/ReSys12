#!/usr/bin/env python3
"""Generates src/s10/s10_games.inc from MAME src/mame/namco/namcos10.cpp (BSD-3-Clause).

The per-game machine configs (board, NAND chips, I/O board, bit unscrambler, decrypter logic) are copied as C++
(lambdas and brace initialisers kept verbatim), the ROM_START blocks become file tables, the GAME lines the set list.

  tools/gen_s10_games.py [path/to/namcos10.cpp] > src/s10/s10_games.inc
"""
import os, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Documents/Dev/mame/src/mame/namco/namcos10.cpp")
text = open(src).read()


def braced(s, i):
    """s[i] == '{': the text up to its matching '}' (inclusive)."""
    depth = 0
    for j in range(i, len(s)):
        depth += {"{": 1, "}": -1}.get(s[j], 0)
        if depth == 0:
            return s[i:j + 1]
    raise ValueError("unbalanced")


BOARD = {"namcos10_memn_base": "S10_MEMN", "namcos10_memp3_base": "S10_MEMP3", "namcos10_memio_base": "S10_MEMIO",
         "namcos10_memm": "S10_MEMM"}
IO = {"namcos10_exio": "S10_IO_EXIO", "namcos10_mgexio": "S10_IO_MGEXIO", "namcos10_exfinalio": "S10_IO_EXFINAL"}
NAND = {"k9f2808u0b": "S10_K9F2808U0B", "k9f5608u0d": "S10_K9F5608U0D", "tc58256aft": "S10_TC58256AFT"}

out = ["// Generated by tools/gen_s10_games.py from MAME src/mame/namco/namcos10.cpp (BSD-3-Clause,",
       "// copyright-holders: smf, windyfairy, Andreas Naive, ...). Do not edit.", ""]
cfgs = {}
for m in re.finditer(r"void namcos10_\w+_state::(ns10_\w+)\(machine_config &config\)\n\{", text):
    name = m.group(1)
    body = braced(text, m.end() - 1)
    board = next((v for k, v in BOARD.items() if re.search(r"\b%s\(config\)" % k, body)), None)
    io = next((v for k, v in IO.items() if re.search(r"\b%s\(config\)" % k, body)), "S10_IO_NONE")
    nm = re.search(r"namcos10_nand_(\w+)\(config, (\d+)\)", body)
    nand, count = (NAND[nm.group(1)], int(nm.group(2))) if nm else ("S10_K9F2808U0B", 0)
    um = re.search(r"m_unscrambler = (\[\] \(uint16_t data\) \{.*?\});", body)
    if name == "ns10_mrdrilr2":  # (its unscrambler is set by init_mrdrilr2)
        um = re.search(r"m_unscrambler = (\[\] \(uint16_t data\) \{.*?\});", text[text.index("::init_mrdrilr2"):])
    unscr = "unscr_%s" % name[5:]
    out.append("static uint16_t %s(uint16_t data) { return (%s)(data); }" % (unscr, um.group(1) if um else "[] (uint16_t d) { return d; }"))
    dec, logic = "S10_DEC_NONE", "nullptr"
    dm = re.search(r"NS10_TYPE2_DECRYPTER(_NONLINEAR)?\(config, m_decrypter, 0, \w+::ns10_crypto_logic\{", body)
    if dm:
        nl = bool(dm.group(1))
        dec = "S10_DEC_TYPE2_NONLINEAR" if nl else "S10_DEC_TYPE2"
        logic = "logic_%s" % name[5:]
        out.append("static const %s %s = %s;" % ("ns10_logic_nl" if nl else "ns10_logic", logic, braced(body, dm.end() - 1)))
        logic = "&" + logic
    elif "MRDRILR2_DECRYPTER" in body:
        dec = "S10_DEC_TYPE1"
    cfgs[name] = "{ %s, %s, %s, %d, %s, %s, %s }" % (board, io, nand, count, unscr, dec, logic)

out += ["", "static const S10Config k_s10_configs[] = {"]
cfg_index = {}
for i, (name, c) in enumerate(cfgs.items()):
    cfg_index[name] = i
    out.append("\t%s, // %d %s" % (c, i, name))
out += ["};", ""]

REGION = {"nand": "S10_RGN_NAND", "data": "S10_RGN_DATA", "decrypter:nonlinear_table": "S10_RGN_NONLINEAR",
          "nvram": "S10_RGN_NVRAM", "exio:nvram": "S10_RGN_NVRAM"}
roms, disks = {}, {}
for m in re.finditer(r"ROM_START\( *(\w+) *\)(.*?)ROM_END", text, re.S):
    files, rgn = [], None
    for line in m.group(2).split("\n"):
        r = re.search(r"ROM_REGION\w*\( *(0x[0-9a-fA-F]+), *\"([^\"]+)\"", line)
        if r:
            n = r.group(2)
            rgn = REGION.get(n) or ("S10_RGN_NAND0 + %s" % n[4:] if re.fullmatch(r"nand\d+", n) else None)
            continue
        f = re.search(r"ROM_LOAD\( *\"([^\"]+)\", *(0x[0-9a-fA-F]+), *(0x[0-9a-fA-F]+), *(?:BAD_DUMP *)?CRC\(([0-9a-fA-F]+)\)", line)
        if f and rgn:
            files.append('{ %s, "%s", %s, %s, 0x%s }' % (rgn, f.group(1), f.group(2), f.group(3), f.group(4)))
    roms[m.group(1)] = files
    d = re.search(r"DISK_IMAGE\w*\( *\"([^\"]+)\"", m.group(2)) # (the Taiko CD-ROMs, MAME CHD files)
    disks[m.group(1)] = d.group(1) if d else ""

games = []
for m in re.finditer(r"^GAME\( *(\d+), *(\w+), *(\w+), *(\w+), *(\w+), *\w+, *(\w+), *(ROT\d+), *(\"[^\"]*\"), *(\"[^\"]*\"), *([^)]*)\)", text, re.M):
    year, name, parent, cfg, inp, init, rot, maker, desc, flags = m.groups()
    games.append((name, "" if parent == "0" else parent, cfg_index[cfg], desc, year, "MACHINE_NOT_WORKING" in flags))

for name, *_ in games:
    out.append("static const S10File files_%s[] = {\n\t%s,\n\t{ -1, NULL, 0, 0, 0 },\n};" % (name, ",\n\t".join(roms[name])))
out += ["", "static const S10Game k_s10_games[] = {"]
for name, parent, ci, desc, year, nw in games:
    out.append('\t{ "%s", "%s", %s, "%s", %d, %d, files_%s, "%s" },' % (name, parent, desc, year, ci, int(nw), name, disks[name]))
out += ["};", ""]
print("\n".join(out))
