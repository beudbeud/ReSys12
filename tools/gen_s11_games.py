#!/usr/bin/env python3
# generates src/romload/s11_games.h from MAME src/mame/namco/namcos11.cpp (ROM_START blocks and GAME lines)
import re, sys

src = open(sys.argv[1]).read()
RGN = {"maincpu:rom": "S12_RGN_MAIN", "bankedroms": "S12_RGN_BANK", "c76": "S12_RGN_SUB", "c352": "S12_RGN_C352"}
SIZE_FIELD = {"S12_RGN_MAIN": 0, "S12_RGN_BANK": 1, "S12_RGN_SUB": 2, "S12_RGN_C352": 3}
LOAD = {"ROM_LOAD": "S12_LD_PLAIN", "ROM_LOAD16_BYTE": "S12_LD_16_BYTE", "ROM_LOAD16_WORD_SWAP": "S12_LD_16_WORD_SWAP"}
# machine config -> (map type, keycus)
MACH = {"tekken": ("S12_S_S11_ROM8", "C406"), "tekken2o": ("S12_S_S11_ROM8", "C406"), "tekken2": ("S12_S_S11_ROM8", "C406"),
        "souledge": ("S12_S_S11_ROM8", "C409"), "dunkmnia": ("S12_S_S11_ROM8", "C410"), "primglex": ("S12_S_S11_ROM8", "C411"),
        "xevi3dg": ("S12_S_S11_ROM8", "C430"), "danceyes": ("S12_S_S11_ROM8", "C431"), "pocketrc": ("S12_S_S11_ROM8", "C432"),
        "fambowl": ("S12_S_S11_ROM8", "C432"), "starswep": ("S12_S_S11_NOBANK", "C442"),
        "myangel3": ("S12_S_S11_ROM8_64", "C443"), "ptblank2ua": ("S12_S_S11_ROM8_64", "C443")}

blocks = {}
for m in re.finditer(r"ROM_START\(\s*(\w+)\s*\)(.*?)ROM_END", src, re.S):
    blocks[m.group(1)] = m.group(2)

roms, games = [], []
for m in re.finditer(r'^GAME\(\s*(\d+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*\w+,\s*\w+,\s*ROT(\d+),\s*"([^"]*)",\s*"([^"]*)",\s*([^)]*)\)',
                     src, re.M):
    year, name, parent, mach, inp, rot, maker, title, flags = m.groups()
    if mach not in MACH:
        continue
    state, keycus = MACH[mach]
    sizes = [0, 0, 0, 0]
    start = len(roms)
    rgn = None
    for line in blocks[name].split("\n"):
        line = line.split("//")[0]
        r = re.search(r'ROM_REGION\w*\(\s*(0x[0-9a-fA-F]+),\s*"([^"]+)"', line)
        if r:
            rgn = RGN.get(r.group(2))
            if rgn:
                sizes[SIZE_FIELD[rgn]] = int(r.group(1), 16)
            continue
        if not rgn:
            continue
        r = re.search(r'(ROM_LOAD\w*)\(\s*"([^"]+)",\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*CRC\((\w+)\)', line)
        if r:
            roms.append('\t{ %s, %s, 0, 0x%07x, 0x%07x, 0x%s, "%s" }, // %s' % (rgn, LOAD[r.group(1)], int(r.group(3), 16),
                        int(r.group(4), 16), r.group(5).lower(), r.group(2), name))
            continue
        r = re.search(r'ROM_RELOAD\(\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+)', line)
        if r:
            roms.append('\t{ %s, S12_LD_RELOAD, 0, 0x%07x, 0x%07x, 0, "" }, // %s' % (rgn, int(r.group(1), 16),
                        int(r.group(2), 16), name))
            continue
        # ROM_CONTINUE (dunkmnia, primglex: "first & second half identical"): the loader places e->size bytes only
    inputs = inp
    games.append('\t{ "%s", "%s", "%s", "%s", %s, S12_M_S11, %s, "%s", %s, %s, "%s", 0x%x, 0x%x, 0x%x, 0x%x, %d, %d },' % (
        name, "" if parent == "0" else parent, title, maker, year, state, inputs, rot,
        "S12_G_NOT_WORKING" if "NOT_WORKING" in flags else "0", keycus, sizes[0], sizes[1], sizes[2], sizes[3],
        start, len(roms) - start))

print("// generated by tools/gen_s11_games.py from MAME src/mame/namco/namcos11.cpp (BSD-3-Clause; names, sizes, CRCs only). Do not edit.")
print("// Regions: MAIN = maincpu:rom, BANK = bankedroms, SUB = c76 (sound program), C352 = c352; IOCPU = C76 BIOS")
print("// (namcoc76.zip, s12_rom.c). state = memory map (rom8 / rom8_64 / none), keycus = the ns11prot.cpp device")
print("#ifndef S11_GAMES_H\n#define S11_GAMES_H\n\n#include \"s12_types.h\"\n")
print("static const S12RomEntry s11_roms[] = {")
print("\n".join(roms))
print("};\n\nstatic const S12Game s11_games[] = {")
print("\n".join(games))
print("};\n#define S11_NUM_GAMES ((int)(sizeof(s11_games) / sizeof(s11_games[0])))\n\n#endif")
